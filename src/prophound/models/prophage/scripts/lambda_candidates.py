"""Discovery-facing check on LAMBDA: do the tools' calls reach LAMBDA's reviewed candidates?

docs/claims-and-evidence.md "LAMBDA candidates check". LAMBDA's curated truth is the
elements experts accepted. Its `candidate_prophages` are regions outside that truth,
predicted by LAMBDA's genomic language models and then classified by review (LIKELY,
POSSIBLE, WEAK PHAGE SIGNAL, GENOMIC ISLAND, GENOMIC ISLAND / ICE, UNLIKELY PHAGE).
A LIKELY PHAGE candidate is a phage the reviewers believed but the curated set lacks,
so reaching it is evidence for discovery beyond curated truth.

Per tool and subset:
  recovery   per candidate class, the fraction of candidates with >= 50% of their bp under
             the tool's calls (and with any overlap), against chance: every call on a
             chromosome rotated by one uniform random offset (lambda_chance.py's model),
             averaged over draws. Above chance = observed - chance, with a 95% genome
             bootstrap of per-genome (observed hits - mean chance hits).
  landing    of the tool's calls that overlap no curated element, the fraction overlapping
             each candidate class, against the same rotated calls.
  matched    prophound's calls ranked by max_prob and cut, per genome, to a comparator's call
     cost    count (geNomad, PHASTER), then the recovery above.
Subsets: all genomes; not_in_corpus (no genome in prophound's corpus; primary); candidates
LAMBDA flags as novel. Each tool is scored only on the genomes it ran on.

The candidates were generated by LAMBDA's language models, so the LM tools are scored on
regions they helped produce: their rows are labelled circular and are not comparisons.

  python scripts/lambda_candidates.py --data analysis/external_benchmarks/lambda \\
      --prophound_run analysis/lambda/ens --out analysis/external_benchmarks/lambda/candidates.json
  python scripts/lambda_candidates.py --data ... --check-inputs      # validate inputs, score nothing
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd
from lambda_chance import rotate
from lambda_score import prophound_calls, union_cov

CLASSES = ["LIKELY PHAGE", "POSSIBLE PHAGE", "WEAK PHAGE SIGNAL", "GENOMIC ISLAND", "GENOMIC ISLAND / ICE",
           "UNLIKELY PHAGE"]
COMBINED = {"LIKELY or POSSIBLE PHAGE": ("LIKELY PHAGE", "POSSIBLE PHAGE")}
PROPHOUND = ["prophound exploratory", "prophound default", "prophound conservative"]
MATCHED_TO = ["geNomad", "PHASTER"]
LM_SUFFIX = re.compile(r" (2k|4k|8k)$")   # LAMBDA's language-model tools are named "<model> <window>"
BOOT = 10_000


def load(data: Path) -> dict:
    d = {name: pd.read_csv(data / f"lambda_{name}.tsv", sep="\t")
         for name in ("genomes", "truth", "candidates", "calls", "tools_run")}
    c = d["candidates"]
    # lambda_prepare.py wrote start - 1 for a 1-based start of 0; clamp that sentinel to 0
    d["candidates"] = c.assign(start=c.start.clip(lower=0), novel=c.novel_flag.astype(str) == "True")
    return d


def classes_of(cands: pd.DataFrame) -> dict:
    out = {k: cands[cands.classification == k] for k in CLASSES}
    for name, members in COMBINED.items():
        out[name] = cands[cands.classification.isin(members)]
    return out


def rotated(calls: pd.DataFrame, lengths: dict, rng) -> pd.DataFrame:
    """Every chromosome's calls rotated by one uniform random offset (lambda_chance.py's null)."""
    parts = []
    for seq, cc in calls.groupby("sequence"):
        L = int(lengths[seq])
        parts.append(rotate(cc, L, int(rng.integers(0, L))).assign(sequence=seq))
    return pd.concat(parts, ignore_index=True) if parts else calls.head(0)


def candidate_hits(cands: pd.DataFrame, calls: pd.DataFrame, genomes: pd.DataFrame, draws: int,
                   rng) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Per candidate: observed coverage fraction, and the chance of covered>=50% and of any
    overlap, averaged over rotations."""
    lengths = dict(zip(genomes.sequence, genomes.genome_length))
    hit50, hit_any = np.zeros(len(cands)), np.zeros(len(cands))
    for _ in range(draws):
        f = union_cov(cands, rotated(calls, lengths, rng))
        hit50 += f >= 0.5
        hit_any += f > 0
    return union_cov(cands, calls), hit50 / draws, hit_any / draws


def genome_boot(per_genome_excess: np.ndarray, n_per_genome: np.ndarray, rng) -> list:
    """95% genome bootstrap of (sum of excess hits) / (sum of candidates)."""
    if n_per_genome.sum() == 0:
        return [float("nan")] * 2
    idx = rng.integers(0, len(per_genome_excess), size=(BOOT, len(per_genome_excess)))
    r = per_genome_excess[idx].sum(1) / np.maximum(1, n_per_genome[idx].sum(1))
    return [float(np.percentile(r, 2.5)), float(np.percentile(r, 97.5))]


def summarize(cands: pd.DataFrame, obs: np.ndarray, ch50: np.ndarray, ch_any: np.ndarray, genomes: pd.DataFrame,
              rng) -> list[dict]:
    """Rows per candidate class: observed and chance recovery, above chance, interval."""
    rows, gs = [], list(genomes.assembly)
    for name, sub in classes_of(cands).items():
        i = sub.index.to_numpy()
        if not len(i):
            rows.append({"class": name, "n_candidates": 0})
            continue
        a = cands.assembly.to_numpy()[i]
        hit, chance = (obs[i] >= 0.5).astype(float), ch50[i]
        per_g = np.array([(hit - chance)[a == g].sum() for g in gs])
        n_g = np.array([(a == g).sum() for g in gs], float)
        rows.append({"class": name, "n_candidates": int(len(i)),
                     "covered50": float(hit.mean()), "covered50_chance": float(chance.mean()),
                     "covered50_above_chance": float((hit - chance).mean()),
                     "above_chance_boot95": genome_boot(per_g, n_g, rng),
                     "any_overlap": float((obs[i] > 0).mean()), "any_overlap_chance": float(ch_any[i].mean())})
    return rows


def overlapping(calls: pd.DataFrame, regions: pd.DataFrame) -> np.ndarray:
    """Per call, whether it overlaps any region on its sequence."""
    out = np.zeros(len(calls), dtype=bool)
    by = {s: g[["start", "end"]].to_numpy() for s, g in regions.groupby("sequence")}
    for k, (s, a, b) in enumerate(zip(calls.sequence, calls.start, calls.end)):
        r = by.get(s)
        out[k] = r is not None and bool(((r[:, 1] > a) & (r[:, 0] < b)).any())
    return out


def landing(truth: pd.DataFrame, cands: pd.DataFrame, calls: pd.DataFrame, genomes: pd.DataFrame,
            draws: int, rng) -> dict:
    """Of calls overlapping no curated element, the fraction overlapping each class: observed, and
    the mean for rotated calls."""
    groups = classes_of(cands)

    def fractions(c: pd.DataFrame) -> dict:
        off = c[~overlapping(c, truth)]
        out = {"off_truth_calls": len(off)}
        for name, sub in groups.items():
            out[name] = float(overlapping(off, sub).mean()) if len(off) else float("nan")
        return out
    observed = fractions(calls)
    lengths = dict(zip(genomes.sequence, genomes.genome_length))
    draws_out = [fractions(rotated(calls, lengths, rng)) for _ in range(draws)]
    chance = {k: float(np.nanmean([d[k] for d in draws_out])) for k in observed}
    return {"observed": observed, "chance": chance,
            "enrichment": {k: (observed[k] / chance[k] if chance[k] else float("nan"))
                           for k in observed if k != "off_truth_calls"}}


def matched(calls: pd.DataFrame, comparator: pd.DataFrame, genomes: pd.DataFrame) -> pd.DataFrame:
    """prophound's calls cut, per genome, to the comparator's call count, best max_prob first."""
    k = comparator.groupby("assembly").size()
    keep = [g.sort_values("max_prob", ascending=False).head(int(k.get(a, 0)))
            for a, g in calls.groupby("assembly") if a in set(genomes.assembly)]
    return pd.concat(keep, ignore_index=True) if keep else calls.head(0)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", required=True, help="lambda_prepare.py output dir")
    ap.add_argument("--prophound_run", default=None, help="run dir: <assembly>/windows.tsv with --write-seed-scores")
    ap.add_argument("--draws", type=int, default=1000)
    ap.add_argument("--landing-draws", type=int, default=200, help="rotations for the landing chance (slower)")
    ap.add_argument("--seed", type=int, default=20261020)
    ap.add_argument("--check-inputs", action="store_true", help="validate the inputs and stop; nothing is scored")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    d = load(Path(a.data))
    G, T, CAND, C, RAN = d["genomes"], d["truth"], d["candidates"], d["calls"], d["tools_run"]

    unknown = sorted(set(CAND.classification) - set(CLASSES))
    missing_g = sorted(set(CAND.assembly) - set(G.assembly))
    print(f"[inputs] {len(G)} genomes ({(G.corpus_status == 'not_in_corpus').sum()} not in corpus), "
          f"{len(T)} curated elements, {len(CAND)} candidates by class "
          f"{CAND.classification.value_counts().to_dict()}, {int(CAND.novel.sum())} flagged novel; "
          f"{C.tool.nunique()} published tools")
    if unknown or missing_g:
        raise SystemExit(f"unknown classes {unknown} or candidate genomes not in the genome table {missing_g}")
    if a.check_inputs:
        return
    if not (a.prophound_run and a.out):
        raise SystemExit("--prophound_run and --out are needed to score")

    rng = np.random.default_rng(a.seed)
    tools = {t: C[C.tool == t] for t in sorted(C.tool.unique())}
    ran = {t: set(RAN[RAN.tool == t].assembly) for t in tools}
    for k, v in prophound_calls(a.prophound_run, G).items():
        tools[k], ran[k] = v, set(G.assembly)
    subsets = {"all": G, "not_in_corpus": G[G.corpus_status == "not_in_corpus"]}

    rows, res = [], {"n_candidates": len(CAND), "tools": {}}
    order = PROPHOUND + [t for t in tools if t not in PROPHOUND]
    for tool in order:
        kind = "prophound" if tool in PROPHOUND else ("language model (circular)" if LM_SUFFIX.search(tool)
                                                      else "annotation")
        res["tools"][tool] = {"kind": kind}
        for sname, gs in subsets.items():
            gs = gs[gs.assembly.isin(ran[tool])]
            calls = tools[tool][tools[tool].assembly.isin(gs.assembly)]
            cands = CAND[CAND.assembly.isin(gs.assembly)].reset_index(drop=True)
            obs, ch50, ch_any = candidate_hits(cands, calls, gs, a.draws, rng)
            novel = cands.novel.to_numpy()
            for cname, mask in (("all candidates", np.ones(len(cands), bool)), ("novel-flagged", novel)):
                sub = cands[mask].reset_index(drop=True)
                for r in summarize(sub, obs[mask], ch50[mask], ch_any[mask], gs, rng):
                    rows.append({"tool": tool, "kind": kind, "subset": sname, "candidates": cname,
                                 "n_genomes": len(gs), "calls_per_genome": len(calls) / max(1, len(gs)), **r})
            if tool in PROPHOUND or kind == "annotation":
                res["tools"][tool][f"landing/{sname}"] = landing(T, CAND[CAND.assembly.isin(gs.assembly)], calls, gs,
                                                                 a.landing_draws, rng)
        if tool in PROPHOUND:
            for comp in MATCHED_TO:
                if comp not in tools:
                    continue
                gs = subsets["not_in_corpus"][subsets["not_in_corpus"].assembly.isin(ran[comp])]
                cut = matched(tools[tool], tools[comp], gs)
                cands = CAND[CAND.assembly.isin(gs.assembly)].reset_index(drop=True)
                for r in summarize(cands, *candidate_hits(cands, cut, gs, a.draws, rng), gs, rng):
                    rows.append({"tool": f"{tool} at {comp}'s cost", "kind": "prophound, matched cost",
                                 "subset": "not_in_corpus", "candidates": "all candidates", "n_genomes": len(gs),
                                 "calls_per_genome": len(cut) / max(1, len(gs)), **r})
        print(f"[scored] {tool}", flush=True)

    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    res["recovery"] = rows
    out.write_text(json.dumps(res, indent=2, default=float) + "\n")
    pd.DataFrame(rows).to_csv(out.with_suffix(".csv"), index=False)
    print(f"[done] wrote {out} and {out.with_suffix('.csv')}")


if __name__ == "__main__":
    main()
